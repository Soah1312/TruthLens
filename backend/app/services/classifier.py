"""
TruthLens Phase 2 - Model Inference Service
Provides cached, singleton inference for fine-tuned DistilBERT models.
Supports loading from local directory or Hugging Face Hub.
"""

import os
import logging
from typing import Dict, Any, Optional, Tuple

from app.core.config import settings

logger = logging.getLogger("truthlens.classifier")

# Canonical 6-class labels
LABEL_LIST = [
    "pants-fire",
    "false",
    "barely-true",
    "half-true",
    "mostly-true",
    "true",
]

LABEL2ID = {label: i for i, label in enumerate(LABEL_LIST)}
ID2LABEL = {i: label for i, label in enumerate(LABEL_LIST)}


class ModelNotAvailableError(Exception):
    """Raised when the trained DistilBERT model weights or tokenizer cannot be loaded."""
    pass


class DistilBertClassifierService:
    """
    Singleton inference service that loads the model once into memory and reuses it across requests.
    """

    _instance: Optional["DistilBertClassifierService"] = None

    def __init__(self):
        self.model = None
        self.tokenizer = None
        self.device = None
        self.is_loaded = False
        self.load_error: Optional[str] = None
        self.model_identifier = "distilbert-liar"

    @classmethod
    def get_instance(cls) -> "DistilBertClassifierService":
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance

    def _resolve_model_path(self) -> str:
        """Determines the target path or HF repo based on application configuration."""
        if settings.MODEL_SOURCE.lower() == "huggingface":
            if not settings.HF_MODEL_REPO or "your-username" in settings.HF_MODEL_REPO:
                raise ModelNotAvailableError(
                    "MODEL_SOURCE is set to 'huggingface', but HF_MODEL_REPO is not configured. "
                    "Please set HF_MODEL_REPO to your repository (e.g., username/truthlens-distilbert-liar)."
                )
            return settings.HF_MODEL_REPO
        else:
            # Local directory path relative to project root or absolute
            local_path = settings.LOCAL_MODEL_PATH
            if not os.path.isabs(local_path):
                # Search relative to current working dir or workspace
                base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
                candidate = os.path.join(base_dir, local_path)
                if os.path.exists(candidate):
                    local_path = candidate

            if not os.path.exists(local_path):
                raise ModelNotAvailableError(
                    f"Local model directory not found at: '{local_path}'. "
                    "Please download the trained model archive from Google Colab and extract it to 'models/distilbert-liar', "
                    "or set MODEL_SOURCE='huggingface' and configure HF_MODEL_REPO in your .env."
                )

            # Check that model weights or config exists inside
            has_config = os.path.exists(os.path.join(local_path, "config.json"))
            has_weights = (
                os.path.exists(os.path.join(local_path, "pytorch_model.bin"))
                or os.path.exists(os.path.join(local_path, "model.safetensors"))
            )
            if not (has_config and has_weights):
                raise ModelNotAvailableError(
                    f"Model directory '{local_path}' does not contain expected model files (config.json, model.safetensors or pytorch_model.bin). "
                    "Please extract the full model archive generated by Colab."
                )

            return local_path

    def load_model(self) -> None:
        """
        Loads the pre-trained/fine-tuned tokenizer and sequence classification model.
        Runs once and caches instances.
        """
        if self.is_loaded:
            return

        try:
            import torch
            from transformers import AutoTokenizer, AutoModelForSequenceClassification

            model_location = self._resolve_model_path()
            logger.info("Loading DistilBERT model from source [%s]: %s", settings.MODEL_SOURCE, model_location)

            self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
            self.tokenizer = AutoTokenizer.from_pretrained(model_location)
            self.model = AutoModelForSequenceClassification.from_pretrained(model_location)
            self.model.to(self.device)
            self.model.eval()

            self.is_loaded = True
            self.load_error = None
            logger.info("DistilBERT model loaded successfully into memory on device: %s", self.device)
        except Exception as exc:
            self.is_loaded = False
            self.load_error = str(exc)
            logger.warning("DistilBERT model initialization unavailable: %s", exc)
            raise ModelNotAvailableError(f"Model initialization failed: {exc}") from exc

    def predict(self, text: str) -> Dict[str, Any]:
        """
        Executes actual neural model inference on input text.
        
        Returns:
            Dictionary with prediction label, confidence, all 6 class probabilities, model name, and disclaimer.
        """
        if not self.is_loaded:
            self.load_model()

        import torch

        # Tokenize statement
        inputs = self.tokenizer(
            text,
            truncation=True,
            padding=True,
            max_length=128,
            return_tensors="pt",
        )
        inputs = {k: v.to(self.device) for k, v in inputs.items()}

        # Disable gradients during evaluation
        with torch.no_grad():
            outputs = self.model(**inputs)
            logits = outputs.logits
            probabilities_tensor = torch.softmax(logits, dim=-1).squeeze(0)

        probs_list = probabilities_tensor.cpu().numpy().tolist()

        # Map to all 6 canonical truthfulness labels
        probabilities: Dict[str, float] = {}
        for idx, label in enumerate(LABEL_LIST):
            probabilities[label] = round(float(probs_list[idx]), 4)

        # Identify highest probability class
        predicted_idx = int(torch.argmax(probabilities_tensor).item())
        predicted_label = ID2LABEL.get(predicted_idx, LABEL_LIST[predicted_idx])
        confidence = round(float(probabilities_tensor[predicted_idx].item()), 4)

        return {
            "prediction": predicted_label,
            "confidence": confidence,
            "probabilities": probabilities,
            "model": self.model_identifier,
            "disclaimer": "This is a model prediction, not a verified fact-check.",
        }


# Global singleton instance
classifier_service = DistilBertClassifierService.get_instance()
